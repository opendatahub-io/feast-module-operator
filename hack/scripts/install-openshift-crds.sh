# One field of the CRD_MODULES entry for a module key: $2 is the field
# number (2 = module path, 3 = pinned version). Module keys contain only
# letters, digits, and hyphens, so the anchored pattern is a literal key
# match.
module_field() {
	printf '%s\n' "$CRD_MODULES" | grep -m1 "^${1}|" | cut -d'|' -f"$2"
}

# Path of the selected manifest for one selection-table line: the file the
# pinned controller-gen wrote for this module, package, and resource.
selected_manifest() {
	# $1: module key, $2: package path, $3: generated filename
	printf '%s/%s_%s/%s' "$GENERATED_DIR" "$1" "$(printf '%s' "$2" | tr '/' '_')" "$3"
}

# Path of the annotated apply file for a CRD name: the file actually passed
# to kubectl apply. It is written by prepare_selected_manifests before any
# cluster write and holds the verified manifest plus only the ownership
# annotation.
apply_file_for() {
	# $1: CRD name
	printf '%s/apply/%s.yaml' "$SCRATCH_DIR" "$1"
}

# The single SELECTED_RESOURCES row whose module key is $1 and CRD name
# is $2, matched literally — never as a regular expression, so dots in
# CRD names stay dots and cannot cross-match sibling resources. Prints
# the row and returns 0 on a unique match; prints nothing and returns 1
# when no row matches; fails when more than one matches.
selected_row() {
	# $1: module key, $2: CRD name
	sr_match=""
	while IFS='|' read -r sr_module sr_pkg sr_file sr_crd sr_correct; do
		[ -n "$sr_module" ] || continue
		if [ "$sr_module" = "$1" ] && [ "$sr_crd" = "$2" ]; then
			[ -z "$sr_match" ] ||
				fail "multiple selection rows for ${2} in module ${1}"
			sr_match="${sr_module}|${sr_pkg}|${sr_file}|${sr_crd}|${sr_correct}"
		fi
	done <<EOF
$SELECTED_RESOURCES
EOF
	[ -n "$sr_match" ] || return 1
	printf '%s\n' "$sr_match"
}

# Succeeds when a SHIPPED_MANIFESTS row targets module $1 and CRD name
# $2 — literal comparison, same rule as selected_row.
is_shipped() {
	# $1: module key, $2: CRD name
	while IFS='|' read -r ish_module ish_crd _; do
		[ -n "$ish_module" ] || continue
		if [ "$ish_module" = "$1" ] && [ "$ish_crd" = "$2" ]; then
			return 0
		fi
	done <<EOF
$SHIPPED_MANIFESTS
EOF
	return 1
}

# Report the CRDs that were already applied before a failure, without
# rolling anything back. $1: newline-separated list of applied CRD names.
report_partial() {
	if [ -n "$1" ]; then
		echo "Partial state: the following CRDs were applied and were NOT rolled back:" >&2
		while IFS= read -r partial_crd; do
			[ -n "$partial_crd" ] || continue
			echo "  - ${partial_crd}" >&2
		done <<EOF
$1
EOF
	else
		echo "Partial state: no CRDs were applied." >&2
	fi
}

# Canonical JSON form of one CRD document, used for spec-equivalence
# checks: a single line with sorted keys, status and metadata removed, and
# the documented API-server defaults normalized on whichever side lacks
# them (a 'None' conversion strategy, the derived names.singular and
# names.listKind, versions[].served, and explicit nulls dropped from the
# schema, which structural-schema normalization prunes on persist — e.g.
# the shipped routes CRD's anyOf: null). A multi-document file prints
# more than one line and can never compare equal to a single-document
# apply file. jq sorts the keys, so document key order cannot cause a
# false difference.
canonical_crd_json() {
	# $1: CRD document file (YAML or JSON)
	yq_run -o=json -I=0 '.' "$1" | jq -S -c '
		del(.status, .metadata)
		| del(.. | nulls)
		| .spec
		| if (.conversion == null) or (.conversion == {"strategy": "None"}) then del(.conversion) else . end
		| if .names.singular == null then .names.singular = (.names.kind | ascii_downcase) else . end
		| if .names.listKind == null then .names.listKind = (.names.kind + "List") else . end
		| .versions |= map(if .served == null then .served = true else . end)
	'
}

# True (0) when the persisted CRD in $1 (JSON, as fetched from the
# cluster) is spec-equivalent to the apply file in $2 (YAML). Anything
# unreadable or unparsable is not equivalent — this fails closed.
specs_equivalent() {
	# $1: persisted CRD JSON file, $2: apply file
	local eq_existing eq_expected
	if ! eq_existing="$(canonical_crd_json "$1")" || [ -z "$eq_existing" ]; then
		return 1
	fi
	if ! eq_expected="$(canonical_crd_json "$2")" || [ -z "$eq_expected" ]; then
		fail "could not canonicalize the verified apply file for equivalence checking: $2"
	fi
	[ "$eq_existing" = "$eq_expected" ]
}

# Classify one persisted CRD against the apply file this script would
# apply. Sets CLASSIFY_DECISION to "reuse" (owned by this exact cluster
# with an equivalent spec — it may be kept as is) or "refuse" (anything
# else), with the human-readable reason in CLASSIFY_REASON. Returns 0 in
# both cases: a decision was reached. The caller fails the whole set on
# any refusal, before any write.
classify_existing_crd() {
	# $1: persisted CRD JSON file, $2: apply file
	CLASSIFY_DECISION="refuse"
	CLASSIFY_REASON=""
	local existing_owner
	if [ ! -s "$1" ]; then
		CLASSIFY_REASON="its stored definition is empty or unreadable"
		return 0
	fi
	if ! existing_owner="$(jq -r ".metadata.annotations[\"${OWNER_ANNOTATION}\"] // empty" "$1" 2>/dev/null)"; then
		CLASSIFY_REASON="its stored definition could not be parsed"
		return 0
	fi
	case "$existing_owner" in
	'')
		CLASSIFY_REASON="it carries no ${OWNER_ANNOTATION} annotation (unowned: it was not created by this script for cluster '${KIND_CLUSTER_NAME}')"
		return 0
		;;
	esac
	if [ "$existing_owner" != "$KIND_CLUSTER_NAME" ]; then
		CLASSIFY_REASON="its ${OWNER_ANNOTATION} annotation names a different cluster ('${existing_owner}')"
		return 0
	fi
	if specs_equivalent "$1" "$2"; then
		CLASSIFY_DECISION="reuse"
		CLASSIFY_REASON="same owner (${OWNER_ANNOTATION}=${KIND_CLUSTER_NAME}) and an equivalent spec"
	else
		CLASSIFY_REASON="although owned by this cluster, its stored spec differs from the verified manifest this script would apply"
	fi
}

