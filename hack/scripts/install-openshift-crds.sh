#!/usr/bin/env bash
#
# install-openshift-crds.sh
#
# Generate and apply an explicitly selected set of OpenShift and Prometheus
# Operator API CRDs on an existing Kind cluster. Manifests are regenerated
# with a pinned controller-gen from the pinned CRD source modules in
# CRD_MODULES below; only the resources listed in the selection table are
# ever applied. For resources with a verified complete shipped manifest
# (SHIPPED_MANIFESTS below), the source module's own committed manifest is
# installed instead of the regenerated one, because regeneration was shown
# during generation to drop schema validation the committed manifest
# carries.
#
# This script was generated by the rhai-kind-setup skill and is
# standalone: it requires no sibling scripts or helpers. It targets Bash 3.2
# (no associative arrays, mapfile, or namerefs) and runs on macOS
# (/bin/bash) and Linux.
#
# Steps, in order:
#   1. check the prerequisites this script uses (go, kubectl, jq, the
#      selected container engine, and a few POSIX text tools);
#   2. validate the baked settings and the selected-resource table;
#   3. create a private scratch directory in the system temporary
#      directory with mktemp (removed on exit; nothing is persisted next
#      to this script);
#   4. verify the named Kind cluster exists via the pinned kind version,
#      export that cluster's kubeconfig into the private scratch
#      directory, and pass that kubeconfig to every kubectl invocation
#      (the global kubeconfig and current context are never used and
#      never changed);
#   5. prepare an isolated scratch Go module requiring every pinned CRD
#      source module (consumer go.mod, go.sum, and workspace settings
#      are never touched) and run the pinned controller-gen once per
#      selected package — a package may generate sibling definitions, but
#      only the explicitly selected files are ever applied;
#   6. install the verified source manifests — committed shipped
#      manifests chosen during generation replace the generated file for
#      their resources (verified to be a single complete
#      CustomResourceDefinition with the expected name first), then the
#      verified per-resource scope corrections marked in the table are
#      applied to the generated manifests as structured edits (a failure
#      in either stops before any write to the cluster) — then every
#      selected manifest is copied into a private apply file that adds
#      only the e2e.feast.dev/owner annotation (the stored spec is
#      verified unchanged by the annotation step; an unowned intermediate
#      is never created on the cluster and annotated afterward);
#   7. classify the entire selected set against the cluster in a
#      read-only preflight before the first apply: a CRD absent from the
#      cluster may be created; a CRD whose ownership annotation names
#      this exact cluster AND whose stored spec is equivalent to the
#      verified apply file (documented API-server defaults normalized)
#      is reused without rewriting; an unowned, differently owned,
#      incompatible, or unreadable CRD stops the whole set before any
#      write — no CRD is applied at all in that case;
#   8. apply each selected CRD that the preflight marked absent, with
#      server-side apply under the stable field manager below (kubectl
#      >= 1.22; client-side apply's last-applied annotation exceeds the
#      API server's 256KB limit on large CRD schemas) and wait a bounded
#      time for it to reach the Established condition. Synthetic
#      permissive CRDs from the table below — extreme-measure stubs for
#      APIs without a known CRD source — would be rendered in scratch
#      before the first apply and applied the same way; their existence
#      is classified by a separate read-only preflight before the first
#      apply.
#
# A failure during apply or wait leaves explicitly reported partial state
# and does not roll back. Existing CRDs are never deleted, recreated,
# force-conflicted, or have their ownership changed to bypass a refusal.
#
# Network is required on first run: the pinned kind, controller-gen, and
# yq tools and the pinned CRD source modules are downloaded by the Go
# toolchain (module sources land in the shared Go module cache; this
# script's module files stay in private scratch). Later runs reuse the
# cache.
#
# Installing a CRD only makes the API server accept and store objects of
# that kind. OpenShift controllers do not exist in Kind; nothing reconciles
# the objects. No controller or platform compatibility is claimed.

