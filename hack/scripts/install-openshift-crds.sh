# ---------------------------------------------------------------------------
# Step 2: validate the baked settings and the selected-resource table
# ---------------------------------------------------------------------------

validate_baked_settings() {
	check_charset "KIND_CLUSTER_NAME" "$KIND_CLUSTER_NAME"
	check_charset "KIND_VERSION" "$KIND_VERSION"
	check_charset "OWNER_ANNOTATION" "$OWNER_ANNOTATION"
	check_charset "FIELD_MANAGER" "$FIELD_MANAGER"
	# Every CRD source module entry must be well-formed and shell-safe.
	local mod_key mod_path mod_version
	MOD_KEYS_SEEN=""
	while IFS='|' read -r mod_key mod_path mod_version; do
		[ -n "$mod_key" ] || continue # tolerate a trailing blank line
		case "$mod_key" in
		'' | *[!A-Za-z0-9-]*) fail "invalid module key in CRD_MODULES: '${mod_key}'" ;;
		esac
		case "|${MOD_KEYS_SEEN}" in
		*"|${mod_key}|") fail "duplicate module key in CRD_MODULES: '${mod_key}'" ;;
		esac
		MOD_KEYS_SEEN="${MOD_KEYS_SEEN}${mod_key}|"
		check_charset "CRD_MODULES ${mod_key} path" "$mod_path"
		check_charset "CRD_MODULES ${mod_key} version" "$mod_version"
	done <<EOF
$CRD_MODULES
EOF
	check_charset "CONTROLLER_GEN_VERSION" "$CONTROLLER_GEN_VERSION"
	check_charset "YQ_VERSION" "$YQ_VERSION"

	local res_module res_pkg res_file res_crd res_correct
	SELECTED_COUNT=0
	SEEN_CRDS=""
	while IFS='|' read -r res_module res_pkg res_file res_crd res_correct; do
		[ -n "$res_module" ] || continue # tolerate a trailing blank line
		case "$res_module" in
		'' | *[!A-Za-z0-9-]*) fail "invalid module key in SELECTED_RESOURCES: '${res_module}'" ;;
		esac
		[ "$(module_field "$res_module" 2)" != "" ] ||
			fail "unknown module key in SELECTED_RESOURCES: '${res_module}' (not defined in CRD_MODULES)"
		case "$res_pkg" in
		'' | *[!A-Za-z0-9/_-]*) fail "invalid package path in SELECTED_RESOURCES: '${res_pkg}'" ;;
		esac
		case "$res_file" in
		'' | *[!A-Za-z0-9._-]*) fail "invalid generated filename for ${res_crd:-<unknown>}: '${res_file}'" ;;
		esac
		case "$res_crd" in
		'' | *[!A-Za-z0-9.-]*) fail "invalid CRD name in SELECTED_RESOURCES: '${res_crd}'" ;;
		esac
		case "$res_correct" in
		yes | no) ;;
		*) fail "invalid scope-correction flag for ${res_crd}: '${res_correct}' (must be yes or no)" ;;
		esac
		# CRD names are globally unique in Kubernetes; a duplicate here would
		# make every per-resource lookup ambiguous. Literal membership test —
		# CRD names cannot contain '|'.
		case "|${SEEN_CRDS}" in
		*"|${res_crd}|") fail "duplicate CRD name in SELECTED_RESOURCES: '${res_crd}'" ;;
		esac
		SEEN_CRDS="${SEEN_CRDS}${res_crd}|"
		SELECTED_COUNT=$((SELECTED_COUNT + 1))
	done <<EOF
$SELECTED_RESOURCES
EOF

	# Every shipped-manifest override must reference a selected resource from
	# a known module. An override cannot be combined with a scope correction:
	# the committed manifest is authoritative for scope.
	local ship_module ship_crd ship_relpath ship_row
	SHIPPED_COUNT=0
	while IFS='|' read -r ship_module ship_crd ship_relpath; do
		[ -n "$ship_module" ] || continue # tolerate a trailing blank line
		case "$ship_module" in
		'' | *[!A-Za-z0-9-]*) fail "invalid module key in SHIPPED_MANIFESTS: '${ship_module}'" ;;
		esac
		[ "$(module_field "$ship_module" 2)" != "" ] ||
			fail "unknown module key in SHIPPED_MANIFESTS: '${ship_module}'"
		case "$ship_crd" in
		'' | *[!A-Za-z0-9.-]*) fail "invalid CRD name in SHIPPED_MANIFESTS: '${ship_crd}'" ;;
		esac
		case "$ship_relpath" in
		'' | *[!A-Za-z0-9._/-]* | *..*)
			fail "invalid relative manifest path in SHIPPED_MANIFESTS for ${ship_crd}: '${ship_relpath}'"
			;;
		esac
		if ! ship_row="$(selected_row "$ship_module" "$ship_crd")"; then
			fail "shipped manifest for ${ship_crd} does not match a selected resource from module ${ship_module}"
		fi
		case "$ship_row" in
		*'|yes')
			fail "shipped manifest for ${ship_crd} cannot be combined with a scope correction (correct-scope=yes)"
			;;
		esac
		SHIPPED_COUNT=$((SHIPPED_COUNT + 1))
	done <<EOF
$SHIPPED_MANIFESTS
EOF

	# Every synthetic entry must be well-formed. The strict per-field patterns
	# matter more here than for generated CRDs: the whole definition is built
	# from these five values.
	local syn_group syn_version syn_kind syn_plural syn_scope syn_name
	SYNTHETIC_COUNT=0
	SYNTHETIC_PAIRS_SEEN=""
	while IFS='|' read -r syn_group syn_version syn_kind syn_plural syn_scope; do
		[ -n "$syn_group" ] || continue # tolerate a trailing blank line
		case "$syn_group" in
		'' | *[!a-z0-9.-]*) fail "invalid API group in SYNTHETIC_RESOURCES: '${syn_group}'" ;;
		esac
		case "$syn_version" in
		v[0-9]*) ;;
		*) fail "invalid version in SYNTHETIC_RESOURCES for ${syn_plural:-<unknown>}: '${syn_version}' (must be v-prefixed)" ;;
		esac
		case "$syn_kind" in
		'' | *[!A-Za-z0-9]* | [a-z]*) fail "invalid Kind in SYNTHETIC_RESOURCES: '${syn_kind}' (alphanumeric, starting uppercase)" ;;
		esac
		case "$syn_plural" in
		'' | *[!a-z0-9-]*) fail "invalid plural in SYNTHETIC_RESOURCES for ${syn_kind}: '${syn_plural}'" ;;
		esac
		case "$syn_scope" in
		Namespaced | Cluster) ;;
		*) fail "invalid scope in SYNTHETIC_RESOURCES for ${syn_plural}: '${syn_scope}' (must be Namespaced or Cluster)" ;;
		esac
		syn_name="${syn_plural}.${syn_group}"
		# Two rows for the same group/plural pair would write the same
		# manifest path and leave the CRD serving only the last version;
		# reject the pair instead of silently dropping a requested version.
		case "|${SYNTHETIC_PAIRS_SEEN}" in
		*"|${syn_group}/${syn_plural}|") fail "duplicate group/plural pair in SYNTHETIC_RESOURCES: '${syn_name}' (a stub serves exactly one version; merge the rows or pick one)" ;;
		esac
		SYNTHETIC_PAIRS_SEEN="${SYNTHETIC_PAIRS_SEEN}${syn_group}/${syn_plural}|"
		# A stub must never replace a real selected CRD: names are globally
		# unique in Kubernetes.
		case "|${SEEN_CRDS}" in
		*"|${syn_name}|") fail "synthetic CRD '${syn_name}' duplicates a CRD name selected in SELECTED_RESOURCES" ;;
		esac
		SYNTHETIC_COUNT=$((SYNTHETIC_COUNT + 1))
	done <<EOF
$SYNTHETIC_RESOURCES
EOF

	# A plan may be synthetic-only (every needed API lacked a verified source
	# module); it must not be entirely empty.
	[ "$((SELECTED_COUNT + SYNTHETIC_COUNT))" -gt 0 ] ||
		fail "SELECTED_RESOURCES and SYNTHETIC_RESOURCES are both empty: at least one CRD must be selected"

	# Distinct selected module/package pairs (newline-separated,
	# 'module-key|package-path'). controller-gen runs once per pair; the same
	# list drives the scratch module's blank imports, and the distinct module
	# keys drive its requires. The '|| true' keeps an empty selection valid
	# (synthetic-only plans): 'grep -v' exits 1 when every input line is
	# filtered out, which 'set -o pipefail' would otherwise treat as fatal.
	DISTINCT_TARGETS="$(printf '%s\n' "$SELECTED_RESOURCES" | { grep -v '^$' || true; } | cut -d'|' -f1,2 | sort -u)"
	DISTINCT_MODULES="$(printf '%s\n' "$DISTINCT_TARGETS" | cut -d'|' -f1 | sort -u)"
}

# ---------------------------------------------------------------------------
# Step 3: private scratch directory
# ---------------------------------------------------------------------------
# Everything this script writes (kubeconfig, module files, generated
# manifests) stays in a unique private directory created by mktemp in the
# system temporary directory (mktemp creates it mode 700), which is removed
# on exit.

setup_scratch() {
	SCRATCH_DIR="$(mktemp -d)" ||
		fail "could not create a private scratch directory with mktemp"

	cleanup() {
		rm -rf "$SCRATCH_DIR"
	}
	trap cleanup EXIT

	KUBECONFIG_FILE="${SCRATCH_DIR}/kubeconfig"
	MODULE_DIR="${SCRATCH_DIR}/module"
	GENERATED_DIR="${SCRATCH_DIR}/generated"
	mkdir -p "$MODULE_DIR" "$GENERATED_DIR"
}

# ---------------------------------------------------------------------------
# Step 4: Kind target discovery (read-only; the first cluster mutation is
# the apply in Step 8)
# ---------------------------------------------------------------------------

discover_kind_target() {
	info "Verifying Kind cluster '${KIND_CLUSTER_NAME}' (kind ${KIND_VERSION})"

	cluster_list="$(kind_run get clusters)" ||
		fail "kind ${KIND_VERSION} could not list clusters; is the container engine daemon running (kind uses the engine selected by your environment)?"

	printf '%s\n' "$cluster_list" | grep -qx "$KIND_CLUSTER_NAME" ||
		fail "Kind cluster '${KIND_CLUSTER_NAME}' was not found. Clusters reported by kind: ${cluster_list:-<none>}"

	if ! kind_run get kubeconfig --name "$KIND_CLUSTER_NAME" >"$KUBECONFIG_FILE"; then
		fail "could not export the kubeconfig of Kind cluster '${KIND_CLUSTER_NAME}'"
	fi
	chmod 600 "$KUBECONFIG_FILE"

	info "Checking cluster reachability through the private kubeconfig"
	if ! readyz_out="$(kctl get --raw /readyz 2>&1)"; then
		fail "cluster '${KIND_CLUSTER_NAME}' is not reachable through the exported kubeconfig: ${readyz_out}"
	fi
}

# ---------------------------------------------------------------------------
# Step 5: generate CRD manifests from the pinned CRD source modules
# ---------------------------------------------------------------------------
# The scratch module requires the exact pinned version of every referenced
# CRD source module. Blank imports of the selected packages let 'go mod
# tidy' pin their full dependency graph so controller-gen can resolve and
# type-check them, exactly as a consumer module would. All module files
# written here are private to scratch; module-cache sources are only ever
# read.

generate_crds() {
	info "Preparing isolated scratch module for the pinned CRD source modules (network required on first run)"
	local mod_key
	while IFS= read -r mod_key; do
		[ -n "$mod_key" ] || continue
		info "  module: $(module_field "$mod_key" 2)@$(module_field "$mod_key" 3)"
	done <<EOF
$DISTINCT_MODULES
EOF

	{
		printf 'package crdinstall\n\n'
		printf '// Blank imports of the selected packages; they exist only to pin the\n'
		printf '// dependency graph of this scratch module for controller-gen.\n'
		printf 'import (\n'
		local imp_module imp_pkg
		while IFS='|' read -r imp_module imp_pkg; do
			[ -n "$imp_module" ] || continue
			printf '\t_ "%s/%s"\n' "$(module_field "$imp_module" 2)" "$imp_pkg"
		done <<EOF
$DISTINCT_TARGETS
EOF
		printf ')\n'
	} >"${MODULE_DIR}/imports.go"

	if ! (
		cd "$MODULE_DIR" &&
			GOWORK=off GOFLAGS='' go mod init example.invalid/crd-install-scratch
	); then
		fail "could not initialize the isolated scratch module"
	fi

	local req_module
	while IFS= read -r req_module; do
		[ -n "$req_module" ] || continue
		if ! (
			cd "$MODULE_DIR" &&
				GOWORK=off GOFLAGS='' go mod edit -require="$(module_field "$req_module" 2)@$(module_field "$req_module" 3)"
		); then
			fail "could not require $(module_field "$req_module" 2)@$(module_field "$req_module" 3) in the isolated scratch module"
		fi
	done <<EOF
$DISTINCT_MODULES
EOF

	if ! (
		cd "$MODULE_DIR" &&
			GOWORK=off GOFLAGS='' go mod tidy
	); then
		fail "could not resolve the pinned CRD source modules in the isolated scratch module"
	fi

	# Resolve every module's source directory once; one small file per module
	# key in private scratch holds the absolute module-cache path. Minimal
	# version selection can pick a higher version than the pin when another
	# module in the graph requires it, so the selected version is compared
	# with the pin — the generated manifests must come from the verified
	# source, or not at all.
	local mod_dir mod_ver
	while IFS= read -r mod_key; do
		[ -n "$mod_key" ] || continue
		if ! mod_dir="$(cd "$MODULE_DIR" && GOWORK=off GOFLAGS='' go list -m -f '{{.Dir}}' "$(module_field "$mod_key" 2)")"; then
			fail "could not resolve the module directory of $(module_field "$mod_key" 2)"
		fi
		if ! mod_ver="$(cd "$MODULE_DIR" && GOWORK=off GOFLAGS='' go list -m -f '{{.Version}}' "$(module_field "$mod_key" 2)")"; then
			fail "could not resolve the selected version of $(module_field "$mod_key" 2)"
		fi
		if [ "$mod_ver" != "$(module_field "$mod_key" 3)" ]; then
			fail "the scratch module selected $(module_field "$mod_key" 2)@${mod_ver}, not the pinned $(module_field "$mod_key" 3); the pin cannot be honored"
		fi
		printf '%s\n' "$mod_dir" >"${SCRATCH_DIR}/moddir.${mod_key}"
	done <<EOF
$DISTINCT_MODULES
EOF

	local gen_module gen_pkg gen_dir
	while IFS='|' read -r gen_module gen_pkg; do
		[ -n "$gen_module" ] || continue
		gen_dir="$(printf '%s_%s' "$gen_module" "$gen_pkg" | tr '/' '_')"
		info "Generating CRD manifests for package ${gen_pkg} of module ${gen_module} with controller-gen ${CONTROLLER_GEN_VERSION}"
		if ! (
			cd "$MODULE_DIR" &&
				GOWORK=off GOFLAGS='' go run "sigs.k8s.io/controller-tools/cmd/controller-gen@${CONTROLLER_GEN_VERSION}" \
					crd \
					"paths=$(<"${SCRATCH_DIR}/moddir.${gen_module}")/${gen_pkg}/..." \
					"output:crd:artifacts:config=${GENERATED_DIR}/${gen_dir}"
		); then
			fail "controller-gen ${CONTROLLER_GEN_VERSION} failed for package ${gen_pkg} of module ${gen_module} (unsupported generation or tool error)"
		fi
	done <<EOF
$DISTINCT_TARGETS
EOF
}

# ---------------------------------------------------------------------------
# Step 6: install the verified source manifests, then annotate the apply
# files
# ---------------------------------------------------------------------------
# Shipped-manifest overrides and scope corrections run over the whole
# selection first, so a failure in either stops before any write to the
# cluster. Only the files named in the selection table are touched;
# sibling definitions are never applied. Every selected manifest is then
# copied into a private apply file carrying only the ownership annotation
# — the canonical form is compared before and after the annotation to
# prove the stored spec is unchanged.

prepare_selected_manifests() {
	local ship_module ship_crd ship_relpath
	# Shipped overrides: replace the generated manifest with the module's own
	# committed manifest, copied verbatim from the pinned module cache. The
	# file is verified to be a single complete CustomResourceDefinition with
	# the expected name and a valid scope before it replaces anything.
	if [ "$SHIPPED_COUNT" -gt 0 ]; then
		info "Installing ${SHIPPED_COUNT} committed shipped manifest(s) chosen during generation"
	fi
	while IFS='|' read -r ship_module ship_crd ship_relpath; do
		[ -n "$ship_module" ] || continue
		ship_src="$(cat "${SCRATCH_DIR}/moddir.${ship_module}")/${ship_relpath}"
		[ -f "$ship_src" ] ||
			fail "shipped manifest for ${ship_crd} not found in module ${ship_module}: ${ship_relpath}"

		local ship_kind ship_name ship_scope ship_row ship_pkg ship_file ship_dest
		if ! ship_kind="$(yq_run '.kind' "$ship_src")"; then
			fail "could not read the shipped manifest for ${ship_crd}: ${ship_relpath}"
		fi
		[ "$ship_kind" = "CustomResourceDefinition" ] ||
			fail "shipped manifest for ${ship_crd} is not a single CustomResourceDefinition document: ${ship_relpath}"
		if ! ship_name="$(yq_run '.metadata.name' "$ship_src")"; then
			fail "could not read the name of the shipped manifest for ${ship_crd}: ${ship_relpath}"
		fi
		[ "$ship_name" = "$ship_crd" ] ||
			fail "shipped manifest for ${ship_crd} declares a different name: '${ship_name}'"
		if ! ship_scope="$(yq_run '.spec.scope' "$ship_src")"; then
			fail "could not read the scope of the shipped manifest for ${ship_crd}: ${ship_relpath}"
		fi
		case "$ship_scope" in
		Namespaced | Cluster) ;;
		*) fail "shipped manifest for ${ship_crd} declares an invalid scope: '${ship_scope}'" ;;
		esac

		if ! ship_row="$(selected_row "$ship_module" "$ship_crd")"; then
			fail "internal inconsistency: shipped manifest for ${ship_crd} passed validation but has no selection row"
		fi
		ship_pkg="$(printf '%s\n' "$ship_row" | cut -d'|' -f2)"
		ship_file="$(printf '%s\n' "$ship_row" | cut -d'|' -f3)"
		ship_dest="$(selected_manifest "$ship_module" "$ship_pkg" "$ship_file")"

		info "  shipped manifest overrides generated output for ${ship_crd} (${ship_relpath})"
		cp "$ship_src" "$ship_dest"
	done <<EOF
$SHIPPED_MANIFESTS
EOF

	local res_module res_pkg res_file res_crd res_correct manifest
	while IFS='|' read -r res_module res_pkg res_file res_crd res_correct; do
		[ -n "$res_module" ] || continue
		manifest="$(selected_manifest "$res_module" "$res_pkg" "$res_file")"

		# Every selected manifest is checked before any write to the cluster,
		# so a missing or empty controller-gen output cannot leave a partial
		# install.
		[ -s "$manifest" ] ||
			fail "expected controller-gen output for ${res_crd} is missing or empty: ${res_file}"

		# Identity checks, mirroring the shipped-manifest path: a wrong
		# sibling manifest or multi-document controller-gen output must
		# never reach the cluster. The pinned yq prints one result per
		# document, so requiring exactly 'CustomResourceDefinition' also
		# enforces a single document.
		local gen_kind gen_name gen_scope
		if ! gen_kind="$(yq_run '.kind' "$manifest")"; then
			fail "could not read the generated manifest for ${res_crd}: ${res_file}"
		fi
		[ "$gen_kind" = "CustomResourceDefinition" ] ||
			fail "generated manifest for ${res_crd} is not a single CustomResourceDefinition document: ${res_file} (read: '${gen_kind}')"
		if ! gen_name="$(yq_run '.metadata.name' "$manifest")"; then
			fail "could not read the name of the generated manifest for ${res_crd}: ${res_file}"
		fi
		[ "$gen_name" = "$res_crd" ] ||
			fail "generated manifest for ${res_crd} declares a different name: '${gen_name}' (${res_file})"
		if ! gen_scope="$(yq_run '.spec.scope' "$manifest")"; then
			fail "could not read the scope of the generated manifest for ${res_crd}: ${res_file}"
		fi
		case "$gen_scope" in
		Namespaced | Cluster) ;;
		*)
			fail "generated manifest for ${res_crd} declares an invalid scope: '${gen_scope}' (${res_file})"
			;;
		esac

		[ "$res_correct" = "yes" ] || continue

		# Verified per-resource correction: this resource is cluster-scoped in
		# real OpenShift but its generated manifest declares Namespaced. The
		# edit is structured — the pinned yq sets spec.scope and the result is
		# read back through the same tool — so controller-gen output
		# formatting changes cannot break it.
		info "Correcting scope (Namespaced -> Cluster) for ${res_crd}"
		if ! yq_run -i '.spec.scope = "Cluster"' "$manifest"; then
			fail "structured scope correction for ${res_crd} failed (yq ${YQ_VERSION})"
		fi
		local corrected_scope
		if ! corrected_scope="$(yq_run '.spec.scope' "$manifest")"; then
			fail "could not read back the corrected scope of ${res_crd} (yq ${YQ_VERSION})"
		fi
		[ "$corrected_scope" = "Cluster" ] ||
			fail "scope correction for ${res_crd} did not result in scope Cluster (read back: '${corrected_scope}')"
	done <<EOF
$SELECTED_RESOURCES
EOF

	# Annotate every selected manifest into the private apply directory.
	# The ownership annotation is part of the initial apply payload — an
	# unowned CRD is never created first and annotated afterward — and the
	# canonical-form comparison proves the annotation changed nothing but
	# metadata (the canonical form drops metadata, so any spec change would
	# make the two forms differ).
	info "Preparing annotated apply files (owner annotation ${OWNER_ANNOTATION}=${KIND_CLUSTER_NAME}, spec unchanged)"
	mkdir -p "${SCRATCH_DIR}/apply"
	while IFS='|' read -r res_module res_pkg res_file res_crd res_correct; do
		[ -n "$res_module" ] || continue
		manifest="$(selected_manifest "$res_module" "$res_pkg" "$res_file")"
		local apply_file spec_before spec_after owner_read
		apply_file="$(apply_file_for "$res_crd")"

		if ! spec_before="$(canonical_crd_json "$manifest")" || [ -z "$spec_before" ]; then
			fail "could not canonicalize the verified manifest for ${res_crd}: ${res_file}"
		fi
		cp "$manifest" "$apply_file"
		if ! yq_run -i ".metadata.annotations.\"${OWNER_ANNOTATION}\" = \"${KIND_CLUSTER_NAME}\"" "$apply_file"; then
			fail "could not add the ${OWNER_ANNOTATION} annotation to the apply file for ${res_crd}"
		fi
		if ! owner_read="$(yq_run ".metadata.annotations.\"${OWNER_ANNOTATION}\"" "$apply_file")"; then
			fail "could not read back the ${OWNER_ANNOTATION} annotation for ${res_crd}"
		fi
		[ "$owner_read" = "$KIND_CLUSTER_NAME" ] ||
			fail "the ${OWNER_ANNOTATION} annotation read-back failed for ${res_crd} (read: '${owner_read}')"
		if ! spec_after="$(canonical_crd_json "$apply_file")" || [ -z "$spec_after" ]; then
			fail "could not canonicalize the annotated apply file for ${res_crd}"
		fi
		[ "$spec_before" = "$spec_after" ] ||
			fail "adding the ${OWNER_ANNOTATION} annotation changed the stored spec of ${res_crd}; refusing to apply"
	done <<EOF
$SELECTED_RESOURCES
EOF
}

# ---------------------------------------------------------------------------
# Step 7: read-only ownership preflight over the whole selected set
# ---------------------------------------------------------------------------
# Every selected CRD name is classified now, before any write, so no read
# — and no read failure — can happen after a write. The CRD name list is
# read once (a failure here stops the script with zero writes); a name
# absent from the list means absent on the cluster, so per-CRD reads
# never need to distinguish "not found" from "cannot read". A name
# present in the list is read individually — at that point any read
# failure is a real error and stops the script before any write.
#
# Outcomes per CRD: absent -> applied in Step 8; present, owned by this
# exact cluster, and spec-equivalent -> reused without rewriting (not
# applied at all); anything else — unowned, differently owned,
# incompatible, or unreadable — fails the whole set before any write.

preflight_classify_selected() {
	info "Classifying ${SELECTED_COUNT} selected CRD(s) against cluster '${KIND_CLUSTER_NAME}' (read-only preflight)"
	local crd_names
	if ! crd_names="$(kctl get crds -o jsonpath='{.items[*].metadata.name}')"; then
		fail "could not list the CRDs of cluster '${KIND_CLUSTER_NAME}' for the ownership preflight; no CRDs were applied"
	fi

	PREFLIGHT_APPLY_ROWS=""
	PREFLIGHT_REUSE_ROWS=""
	local res_module res_pkg res_file res_crd res_correct apply_file existing_file
	while IFS='|' read -r res_module res_pkg res_file res_crd res_correct; do
		[ -n "$res_module" ] || continue
		apply_file="$(apply_file_for "$res_crd")"
		[ -s "$apply_file" ] ||
			fail "internal inconsistency: no prepared apply file for ${res_crd}"

		case " ${crd_names} " in
		*" ${res_crd} "*)
			# The CRD exists: it may be reused only when it is owned by this
			# exact cluster and its stored spec is equivalent to the verified
			# apply file. Anything else refuses the whole set.
			existing_file="${SCRATCH_DIR}/existing-${res_crd}.json"
			if ! kctl get crd "$res_crd" -o json >"$existing_file" 2>"${SCRATCH_DIR}/kubectl-read.err"; then
				fail "could not read the existing CRD '${res_crd}' on cluster '${KIND_CLUSTER_NAME}' ($(cat "${SCRATCH_DIR}/kubectl-read.err")); no CRDs were applied"
			fi
			classify_existing_crd "$existing_file" "$apply_file"
			if [ "$CLASSIFY_DECISION" = "reuse" ]; then
				info "    exists, ${CLASSIFY_REASON}; reusing without rewriting: ${res_crd}"
				PREFLIGHT_REUSE_ROWS="${PREFLIGHT_REUSE_ROWS}${res_crd}
"
			else
				fail "CRD '${res_crd}' already exists on cluster '${KIND_CLUSTER_NAME}' and was refused: ${CLASSIFY_REASON}.
This script never replaces, adopts, deletes, or force-conflicts an existing CRD, and never changes ownership to bypass a refusal. Delete the CRD explicitly (if safe) or reconcile the difference manually, then re-run. No CRDs were applied."
			fi
			;;
		*)
			# Absent from the cluster: this row may be applied in Step 8.
			PREFLIGHT_APPLY_ROWS="${PREFLIGHT_APPLY_ROWS}${res_module}|${res_pkg}|${res_file}|${res_crd}|${res_correct}
"
			;;
		esac
	done <<EOF
$SELECTED_RESOURCES
EOF

	PREFLIGHT_APPLY_COUNT="$(printf '%s' "$PREFLIGHT_APPLY_ROWS" | { grep -c '.' || true; })"
	PREFLIGHT_REUSE_COUNT="$(printf '%s' "$PREFLIGHT_REUSE_ROWS" | { grep -c '.' || true; })"
	info "Preflight complete: ${PREFLIGHT_APPLY_COUNT} CRD(s) to apply, ${PREFLIGHT_REUSE_COUNT} existing owned definition(s) to reuse"
}

# ---------------------------------------------------------------------------
# Step 7b: read-only preflight for the synthetic stubs
# ---------------------------------------------------------------------------
# Same all-before-any-write rule as the selected-set preflight above,
# applied to synthetic stub names when any are configured.

preflight_synthetic() {
	[ "$SYNTHETIC_COUNT" -gt 0 ] || return 0
	info "Checking ${SYNTHETIC_COUNT} synthetic CRD name(s) against cluster '${KIND_CLUSTER_NAME}' (read-only)"
	local crd_names
	if ! crd_names="$(kctl get crds -o jsonpath='{.items[*].metadata.name}')"; then
		fail "could not list the CRDs of cluster '${KIND_CLUSTER_NAME}' for the synthetic-stub preflight; no CRDs were applied"
	fi
	local syn_group syn_version syn_kind syn_plural syn_scope syn_name
	SYN_EXISTING=""
	while IFS='|' read -r syn_group syn_version syn_kind syn_plural syn_scope; do
		[ -n "$syn_group" ] || continue
		syn_name="${syn_plural}.${syn_group}"
		# CRD names never contain spaces, so the space-padded
		# membership test cannot cross-match.
		case " ${crd_names} " in
		*" ${syn_name} "*)
			# The CRD exists: it may be re-applied only if it is
			# itself a synthetic stub. The stored definition must
			# have exactly one version, and that version's
			# openAPIV3Schema must contain nothing but the stub's
			# own two keys — any validation keyword (properties,
			# required, oneOf, ...) beyond type: object with
			# x-kubernetes-preserve-unknown-fields: true marks a
			# real CRD whose schema a stub must never replace.
			local syn_json syn_crd_file syn_ver_count syn_schema_size syn_schema_type syn_schema_preserve
			if ! syn_json="$(kctl get crd "$syn_name" -o yaml 2>&1)"; then
				fail "could not read the existing CRD '${syn_name}' on cluster '${KIND_CLUSTER_NAME}'; no CRDs were applied"
			fi
			syn_crd_file="${SCRATCH_DIR}/existing-crd.yaml"
			printf '%s\n' "$syn_json" >"$syn_crd_file"
			if ! syn_ver_count="$(yq_run '.spec.versions | length' "$syn_crd_file")" ||
				! syn_schema_size="$(yq_run '.spec.versions[0].schema.openAPIV3Schema | length' "$syn_crd_file")" ||
				! syn_schema_type="$(yq_run '.spec.versions[0].schema.openAPIV3Schema.type' "$syn_crd_file")" ||
				! syn_schema_preserve="$(yq_run '.spec.versions[0].schema.openAPIV3Schema."x-kubernetes-preserve-unknown-fields"' "$syn_crd_file")"; then
				fail "could not parse the existing CRD '${syn_name}' with yq ${YQ_VERSION}; no CRDs were applied"
			fi
			if [ "$syn_ver_count" != "1" ] ||
				[ "$syn_schema_size" != "2" ] ||
				[ "$syn_schema_type" != "object" ] ||
				[ "$syn_schema_preserve" != "true" ]; then
				fail "CRD '${syn_name}' already exists on cluster '${KIND_CLUSTER_NAME}' and is not a synthetic permissive stub (found ${syn_ver_count} version(s); schema with ${syn_schema_size} keys, type '${syn_schema_type}', x-kubernetes-preserve-unknown-fields '${syn_schema_preserve}'; a stub is exactly one version whose schema holds nothing but type: object and x-kubernetes-preserve-unknown-fields: true). A stub never replaces an existing CRD schema: delete the existing CRD explicitly or remove the synthetic row. No CRDs were applied."
			fi
			SYN_EXISTING="${SYN_EXISTING}${syn_name}|"
			;;
		esac
	done <<EOF
$SYNTHETIC_RESOURCES
EOF
}

# ---------------------------------------------------------------------------
# Step 8: apply the selected CRDs the preflight marked absent
# ---------------------------------------------------------------------------
# Only absent definitions are applied; equivalent owned definitions were
# reused without rewriting in the preflight. Every apply is server-side
# under the stable field manager, without forced conflicts, and is
# followed by a bounded wait for the Established condition.

apply_selected() {
	info "Applying ${PREFLIGHT_APPLY_COUNT} selected CRD(s) to cluster '${KIND_CLUSTER_NAME}' (reusing ${PREFLIGHT_REUSE_COUNT} existing owned definition(s))"
	APPLIED_CRDS=""
	local res_module res_pkg res_file res_crd res_correct apply_file apply_out wait_out
	while IFS='|' read -r res_module res_pkg res_file res_crd res_correct; do
		[ -n "$res_module" ] || continue
		apply_file="$(apply_file_for "$res_crd")"

		if is_shipped "$res_module" "$res_crd"; then
			echo "    apply: ${res_crd} (shipped manifest, field manager ${FIELD_MANAGER})"
		else
			echo "    apply: ${res_crd} (field manager ${FIELD_MANAGER})"
		fi
		if ! apply_out="$(kctl apply --server-side --field-manager "$FIELD_MANAGER" -f "$apply_file" 2>&1)"; then
			echo "ERROR: applying ${res_crd} failed: ${apply_out}" >&2
			report_partial "$APPLIED_CRDS"
			fail "installation stopped; no rollback was performed and no conflicts were forced"
		fi

		# Record the write as soon as the apply succeeds: a later wait
		# timeout must still report this CRD as applied.
		APPLIED_CRDS="${APPLIED_CRDS}${res_crd}
"

		if ! wait_out="$(kctl wait --for=condition=Established --timeout="$CRD_ESTABLISHED_TIMEOUT" "crd/${res_crd}" 2>&1)"; then
			echo "ERROR: ${res_crd} did not reach Established within ${CRD_ESTABLISHED_TIMEOUT}: ${wait_out}" >&2
			report_partial "$APPLIED_CRDS"
			fail "installation stopped; no rollback was performed"
		fi
	done <<EOF
$PREFLIGHT_APPLY_ROWS
EOF
}

# ---------------------------------------------------------------------------
# Step 6b: render the synthetic permissive CRDs (before any cluster write)
# ---------------------------------------------------------------------------
# Each stub is a minimal structural-schema CRD: the API server accepts and
# stores any spec/status (x-kubernetes-preserve-unknown-fields), with a
# status subresource so status updates behave like a real operator CRD.
# Nothing validates, defaults, or reconciles these objects. Rendering
# happens before the first cluster write, so a local rendering failure
# cannot happen after the cluster has been modified. This plan configures
# no synthetic stubs, so this function returns immediately.

render_synthetic_manifests() {
	[ "$SYNTHETIC_COUNT" -gt 0 ] || return 0
	info "Writing ${SYNTHETIC_COUNT} synthetic permissive CRD(s) (stubs: no schema validation, no defaulting, no controllers)"
	mkdir -p "${GENERATED_DIR}/synthetic"
	local syn_group syn_version syn_kind syn_plural syn_scope syn_name syn_manifest
	while IFS='|' read -r syn_group syn_version syn_kind syn_plural syn_scope; do
		[ -n "$syn_group" ] || continue
		syn_name="${syn_plural}.${syn_group}"
		syn_manifest="${GENERATED_DIR}/synthetic/${syn_name}.yaml"
		cat >"$syn_manifest" <<EOF
apiVersion: apiextensions.k8s.io/v1
kind: CustomResourceDefinition
metadata:
  name: ${syn_name}
spec:
  group: ${syn_group}
  names:
    kind: ${syn_kind}
    plural: ${syn_plural}
  scope: ${syn_scope}
  versions:
  - name: ${syn_version}
    served: true
    storage: true
    subresources:
      status: {}
    schema:
      openAPIV3Schema:
        type: object
        x-kubernetes-preserve-unknown-fields: true
EOF
	done <<EOF
$SYNTHETIC_RESOURCES
EOF
}

# ---------------------------------------------------------------------------
# Step 8b: apply the pre-rendered synthetic permissive CRDs
# ---------------------------------------------------------------------------
# Existence and stub identity were decided by the read-only preflight
# above, before any write to the cluster.

apply_synthetic() {
	[ "$SYNTHETIC_COUNT" -gt 0 ] || return 0
	info "Applying ${SYNTHETIC_COUNT} synthetic permissive CRD(s)"
	local syn_group syn_version syn_kind syn_plural syn_scope syn_name syn_manifest apply_out wait_out
	while IFS='|' read -r syn_group syn_version syn_kind syn_plural syn_scope; do
		[ -n "$syn_group" ] || continue
		syn_name="${syn_plural}.${syn_group}"
		syn_manifest="${GENERATED_DIR}/synthetic/${syn_name}.yaml"

		case "|${SYN_EXISTING}" in
		*"|${syn_name}|")
			echo "    exists as a synthetic stub; re-applying in place: ${syn_name}"
			;;
		esac

		echo "    apply: ${syn_name} (synthetic stub)"
		if ! apply_out="$(kctl apply --server-side --field-manager "$FIELD_MANAGER" -f "$syn_manifest" 2>&1)"; then
			echo "ERROR: applying synthetic CRD ${syn_name} failed: ${apply_out}" >&2
			report_partial "$APPLIED_CRDS"
			fail "installation stopped; no rollback was performed and no conflicts were forced"
		fi

		# Record the write as soon as the apply succeeds: a later wait
		# timeout must still report this CRD as applied.
		APPLIED_CRDS="${APPLIED_CRDS}${syn_name} (synthetic stub)
"

		if ! wait_out="$(kctl wait --for=condition=Established --timeout="$CRD_ESTABLISHED_TIMEOUT" "crd/${syn_name}" 2>&1)"; then
			echo "ERROR: synthetic CRD ${syn_name} did not reach Established within ${CRD_ESTABLISHED_TIMEOUT}: ${wait_out}" >&2
			report_partial "$APPLIED_CRDS"
			fail "installation stopped; no rollback was performed"
		fi
	done <<EOF
$SYNTHETIC_RESOURCES
EOF
}

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------

summary() {
	info "Done: ${PREFLIGHT_APPLY_COUNT} selected CRD(s) applied (${SHIPPED_COUNT} from shipped manifests), ${PREFLIGHT_REUSE_COUNT} existing owned definition(s) reused, and ${SYNTHETIC_COUNT} synthetic CRD(s) installed and Established on cluster '${KIND_CLUSTER_NAME}':"
	local applied_crd
	while IFS= read -r applied_crd; do
		[ -n "$applied_crd" ] || continue
		echo "  - ${applied_crd}"
	done <<EOF
$APPLIED_CRDS
EOF
}

# ---------------------------------------------------------------------------
# Main flow
# ---------------------------------------------------------------------------

main() {
	check_prerequisites            # Step 1
	validate_baked_settings        # Step 2
	setup_scratch                  # Step 3
	discover_kind_target           # Step 4
	generate_crds                  # Step 5
	prepare_selected_manifests     # Step 6
	render_synthetic_manifests     # Step 6b (inert with no stubs)
	preflight_classify_selected    # Step 7 (read-only; refuses before any write)
	preflight_synthetic            # Step 7b (read-only; inert with no stubs)
	apply_selected                 # Step 8
	apply_synthetic                # Step 8b (inert with no stubs)
	summary
}

