#!/usr/bin/env bash
#
# setup-service-certs.sh
#
# Create — or reuse — explicit Service TLS stand-ins on an existing Kind
# cluster: a local test CA and a CA-signed 30-day serving certificate,
# published as a 'kubernetes.io/tls' Secret and a CA-bundle ConfigMap.
#
# This stand-in exists because the RHOAI operand deployed by this
# repository's e2e suite mounts the Secret named by the metrics Service's
# service.beta.openshift.io/serving-cert-secret-name annotation
# (controller-manager-metrics-tls) and reads the CA bundle from the
# openshift-service-ca.crt ConfigMap: on OpenShift the service-ca
# controller issues that material, and Kind has no such issuer.
#
# Generated by the rhai-kind-setup skill from
# templates/scripts/setup-service-certs.sh.tmpl. Standalone: it requires no
# sibling scripts, no unshipped helper, and only Bash 3.2+ plus the
# prerequisites listed below. All settings are baked into the block at the
# top of this file.
#
# Runtime contract:
#   * Targets only the named Kind cluster, verified through the pinned Kind
#     CLI before any mutation. Every kubectl call uses a private kubeconfig
#     exported into scratch; the ambient kubectl context and the global
#     kubeconfig are never read or changed.
#   * Neither object exists -> create the namespace (if absent), a test CA,
#     the serving certificate, the TLS Secret, and the CA ConfigMap.
#   * Both objects exist and pass validation -> no writes at all.
#   * Exactly one object exists, or validation fails -> nonzero exit with
#     actionable diagnostics; existing material is never replaced, adopted,
#     or deleted.
#   * Authorization, network, and other read errors are never treated as
#     absence. A partial creation failure is reported explicitly,
#     distinguishing confirmed writes from creates whose outcome is
#     unknown (kubectl can fail after the API server stored the object);
#     there is no rollback and no automatic retry.
#   * The Service named below does not need to exist: the certificate simply
#     covers its DNS names. No OpenShift service-ca controller, injector,
#     annotation scanning, rotation, or cert-manager is involved.
#
# Prerequisites (checked at startup, only the ones used): Bash, kubectl,
# openssl, jq, go, and a working container engine backing the Kind cluster.
# The first run may download the pinned sigs.k8s.io/kind module into the
# shared Go module cache; cached sources are never edited or removed.
#
# Private material (CA key, serving key, kubeconfig) lives only in a private
# scratch directory created by mktemp in the system temporary directory and
# removed on exit; it is never printed and never persisted next to this
# script.

set -euo pipefail
umask 077

# ---------------------------------------------------------------------------
# Settings (substituted by the rhai-kind-setup skill — review and adjust)
# ---------------------------------------------------------------------------

# The configured tuple: exactly one namespace/Service/Secret/ConfigMap set.
# These names match the operand this repository's RHOAI overlay deploys:
# the feast-operator- name prefix comes from the kustomize namePrefix, the
# Secret name from the metrics Service's serving-cert-secret-name
# annotation (which the operand Deployment mounts), and the CA ConfigMap
# name/key from the ServiceMonitor's TLS CA config.
NAMESPACE="opendatahub-feast-system"               # created if absent
SERVICE_NAME="feast-operator-controller-manager-metrics-service" # may not exist yet
TLS_SECRET_NAME="controller-manager-metrics-tls"   # kubernetes.io/tls Secret
CA_CONFIGMAP_NAME="openshift-service-ca.crt"       # CA bundle ConfigMap
CLUSTER_DNS_DOMAIN="cluster.local"                 # e.g. cluster.local

# Kind targeting: the exact existing cluster and pinned version. The
# container engine (docker, podman, ...) is deliberately not a baked
# setting: kind selects its engine from the environment
# (KIND_EXPERIMENTAL_PROVIDER when set, otherwise autodetection — docker
# first, then nerdctl, then podman in recent versions), and this script
# never sets or forces that choice, so the same generated script works
# in any environment, with whatever engine backs the user's cluster.
# The cluster name below is the only cluster identity.
KIND_CLUSTER_NAME="feast-module-operator-e2e"
KIND_VERSION="v0.33.0"               # e.g. v0.20.0

# Fixed certificate policy (not collected by the skill).
TLS_SECRET_TYPE="kubernetes.io/tls"
CA_CONFIGMAP_KEY="service-ca.crt"             # ConfigMap key holding the CA cert
LEAF_CERT_VALIDITY_DAYS=30                    # serving certificate lifetime
CA_CERT_VALIDITY_DAYS=90                      # test CA; must outlive the leaf

# Derived Service DNS identities (both must appear in the leaf SANs).
SAN_SHORT="${SERVICE_NAME}.${NAMESPACE}.svc"
SAN_LONG="${SAN_SHORT}.${CLUSTER_DNS_DOMAIN}"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

info() {
    echo "setup-service-certs: $*"
}

die() {
    echo "setup-service-certs: error: $*" >&2
    exit 1
}

cleanup_scratch() {
    # Removes the private scratch directory (keys, kubeconfig).
    if [ -d "${SCRATCH:-}" ]; then
        rm -rf -- "${SCRATCH}"
    fi
}

valid_dns_label() {
    # DNS-1123 label: lowercase alphanumerics and '-', bounded, max 63 chars.
    case "$1" in
        "" | -* | *-) return 1 ;;
        *[!a-z0-9-]*) return 1 ;;
    esac
    [ "${#1}" -le 63 ]
}

valid_dns_subdomain() {
    # DNS subdomain: labels joined by '.', max 253 chars.
    case "$1" in
        "" | -* | *- | .* | *. | *..*) return 1 ;;
        *[!a-z0-9.-]*) return 1 ;;
    esac
    [ "${#1}" -le 253 ]
}

validate_settings() {
    # Fail fast on settings that could not be used safely in file names,
    # openssl configs, or kubectl. Every setting is validated, so an
    # unsubstituted template placeholder is rejected here too — with its
    # raw value visible in the error.
    valid_dns_label "${NAMESPACE}" \
        || die "NAMESPACE '${NAMESPACE}' is not a valid DNS-1123 label."
    valid_dns_label "${SERVICE_NAME}" \
        || die "SERVICE_NAME '${SERVICE_NAME}' is not a valid DNS-1123 label."
    valid_dns_label "${KIND_CLUSTER_NAME}" \
        || die "KIND_CLUSTER_NAME '${KIND_CLUSTER_NAME}' is not a valid DNS-1123 label."
    valid_dns_subdomain "${TLS_SECRET_NAME}" \
        || die "TLS_SECRET_NAME '${TLS_SECRET_NAME}' is not a valid object name."
    valid_dns_subdomain "${CA_CONFIGMAP_NAME}" \
        || die "CA_CONFIGMAP_NAME '${CA_CONFIGMAP_NAME}' is not a valid object name."
    valid_dns_subdomain "${CLUSTER_DNS_DOMAIN}" \
        || die "CLUSTER_DNS_DOMAIN '${CLUSTER_DNS_DOMAIN}' is not a valid DNS domain."

    case "${KIND_VERSION}" in
        v[0-9]*.[0-9]*.[0-9]*) ;;
        *) die "KIND_VERSION '${KIND_VERSION}' must look like 'v0.20.0'." ;;
    esac
}

check_prerequisites() {
    # Only the external commands this script actually uses.
    local command_name
    for command_name in kubectl openssl jq go grep sed cut mktemp; do
        command -v "${command_name}" >/dev/null 2>&1 \
            || die "required command '${command_name}' was not found in PATH."
    done
}

setup_private_scratch() {
    # Private scratch in the system temporary directory (mktemp creates it
    # mode 700 and returns an absolute path).
    SCRATCH="$(mktemp -d)" \
        || die "cannot create a private scratch directory with mktemp."

    # Remove the private scratch directory (keys, kubeconfig) on any exit.
    trap cleanup_scratch EXIT
    trap 'cleanup_scratch; exit 130' INT
    trap 'cleanup_scratch; exit 143' TERM

    # The kubeconfig exported from the named Kind cluster. Every kubectl call
    # in this script passes it explicitly; the ambient context is never used.
    KCFG=(--kubeconfig "${SCRATCH}/kubeconfig")
}

run_kind() {
    # Pinned Kind CLI; never '@latest', never a binary download. GOWORK and
    # GOFLAGS are cleared so consumer Go workspaces and flags cannot
    # interfere. Module downloads use the shared Go module cache.
    GOWORK=off GOFLAGS='' \
        go run "sigs.k8s.io/kind@${KIND_VERSION}" "$@"
}

cert_has_dns_san() {
    # cert_has_dns_san <certificate-file> <dns-name>
    # True when the leaf's subjectAltName extension lists DNS:<dns-name>.
    # The extraction stays inside the SAN extension (everything before its
    # header is dropped; the rest is cut at the next extension header or
    # non-indented line), so a name in another extension — issuerAltName,
    # for example — cannot satisfy the check ('-ext subjectAltName' is not
    # available on LibreSSL). The match is bounded on both sides, so
    # 'a.svc' cannot be satisfied by 'a.svc.cluster.local'.
    # Here-string, not a pipe: under 'set -o pipefail' an early 'grep'
    # match could SIGPIPE the writer.
    local cert_file="$1" dns_name="$2" san_block escaped
    san_block="$(openssl x509 -in "${cert_file}" -noout -text 2>/dev/null \
        | sed -e '1,/X509v3 Subject Alternative Name/d' \
        | sed -e '/^ *X509v3 /,$d' -e '/^[^ ]/,$d')"
    escaped="${dns_name//./\\.}"
    grep -Eq "(^|[ ,])DNS:${escaped}([^A-Za-z0-9.-]|$)" <<<"${san_block}"
}

validate_pair() {
    # validate_pair <ca.crt> <leaf.crt> <leaf.key>
    # Returns 0 when the pair is a usable TLS-server pair for this Service;
    # otherwise returns 1 with the reason in PAIR_ERROR. 'openssl verify'
    # covers expiry, parseability, and chain purpose in one check. Uses
    # only operations common to macOS LibreSSL and Linux OpenSSL
    # ('openssl pkey' with an 'openssl rsa' fallback for public keys).
    local ca_file="$1" leaf_file="$2" key_file="$3"
    local cert_pub key_pub

    cert_pub="$(openssl x509 -in "${leaf_file}" -noout -pubkey 2>/dev/null)" || true
    key_pub="$(openssl pkey -in "${key_file}" -pubout 2>/dev/null \
        || openssl rsa -in "${key_file}" -pubout 2>/dev/null)" || true
    if [ -z "${cert_pub}" ] || [ "${cert_pub}" != "${key_pub}" ]; then
        PAIR_ERROR="the private key does not match the serving certificate's public key (or the key or certificate is unreadable)."
        return 1
    fi
    if ! openssl verify -purpose sslserver -CAfile "${ca_file}" "${leaf_file}" >/dev/null 2>&1; then
        PAIR_ERROR="the serving certificate is not trusted for TLS-server use by this CA (broken or expired chain, missing serverAuth purpose, or an unsuitable CA)."
        return 1
    fi
    # A CA certificate must never serve as the leaf: 'openssl verify
    # -purpose sslserver' alone accepts a CA:TRUE certificate that also
    # carries serverAuth and the expected SANs (reproduced with a
    # self-signed CA:TRUE certificate), so the leaf's basicConstraints
    # are checked explicitly. Text output is used because 'x509 -ext'
    # is a modern-only flag the templates avoid; a certificate without
    # a basicConstraints extension is not a CA and stays acceptable.
    if openssl x509 -in "${leaf_file}" -noout -text 2>/dev/null \
        | grep -A1 'Basic Constraints' | grep -q 'CA:TRUE'; then
        PAIR_ERROR="the serving certificate has basicConstraints CA:TRUE — a CA certificate must not be reused as a serving leaf."
        return 1
    fi
    if ! cert_has_dns_san "${leaf_file}" "${SAN_SHORT}"; then
        PAIR_ERROR="the serving certificate does not list 'DNS:${SAN_SHORT}' in subjectAltName."
        return 1
    fi
    if ! cert_has_dns_san "${leaf_file}" "${SAN_LONG}"; then
        PAIR_ERROR="the serving certificate does not list 'DNS:${SAN_LONG}' in subjectAltName."
        return 1
    fi
}

discover_kind_target() {
    # Verify the exact named cluster exists through the pinned Kind CLI,
    # then export its kubeconfig into private scratch. A 'kind-' context
    # name prefix alone is never trusted, and the ambient context is never
    # used. The container provider is not set or forced: kind uses the
    # engine selected by the user's environment
    # (KIND_EXPERIMENTAL_PROVIDER when set, otherwise autodetection —
    # see the Kind targeting comment at the top of the script).

    info "Targeting Kind cluster '${KIND_CLUSTER_NAME}' (kind ${KIND_VERSION})."
    info "'go run sigs.k8s.io/kind@${KIND_VERSION}' may download the Kind module on first use (shared Go module cache)."

    local clusters
    if ! clusters="$(run_kind get clusters 2>"${SCRATCH}/kind.err")"; then
        die "cannot list Kind clusters (kind ${KIND_VERSION}):
$(cat "${SCRATCH}/kind.err")"
    fi
    # Here-string, not a pipe: 'grep -q' exiting on a match could SIGPIPE the
    # writer under 'set -o pipefail'.
    if ! grep -Fxq "${KIND_CLUSTER_NAME}" <<<"${clusters}"; then
        die "Kind cluster '${KIND_CLUSTER_NAME}' was not found. Existing clusters: [${clusters}]"
    fi

    if ! run_kind export kubeconfig --name "${KIND_CLUSTER_NAME}" \
        --kubeconfig "${SCRATCH}/kubeconfig" \
        >"${SCRATCH}/kind-export.out" 2>"${SCRATCH}/kind-export.err"; then
        die "exporting the kubeconfig of Kind cluster '${KIND_CLUSTER_NAME}' failed:
$(cat "${SCRATCH}/kind-export.err")"
    fi

    # The exported kubeconfig must actually reach the cluster before any
    # object is read or written.
    if ! kubectl "${KCFG[@]}" cluster-info \
        >"${SCRATCH}/cluster-info.out" 2>"${SCRATCH}/cluster-info.err"; then
        die "the kubeconfig exported for Kind cluster '${KIND_CLUSTER_NAME}' does not reach the cluster:
$(cat "${SCRATCH}/cluster-info.err")"
    fi
    info "Kind cluster '${KIND_CLUSTER_NAME}' verified; every kubectl call below uses its private kubeconfig."
}

read_object() {
    # read_object <kind> <name> <namespace-or-empty> <json-out-file>
    # Sets READ_STATUS to 'found', 'missing', or 'error' (plus READ_ERROR).
    # 'missing' means kubectl reported NotFound and nothing else; Forbidden,
    # connection, and other failures are 'error' and are never treated as
    # absence.
    local kind="$1" name="$2" namespace="$3" json_file="$4"
    local -a cmd
    cmd=(kubectl "${KCFG[@]}" get "${kind}" "${name}" -o json)
    if [ -n "${namespace}" ]; then
        cmd+=(-n "${namespace}")
    fi

    READ_STATUS=""
    READ_ERROR=""
    if "${cmd[@]}" >"${json_file}" 2>"${SCRATCH}/kubectl-read.err"; then
        READ_STATUS="found"
    elif grep -q '(NotFound)' "${SCRATCH}/kubectl-read.err"; then
        READ_STATUS="missing"
    else
        READ_STATUS="error"
        READ_ERROR="$(cat "${SCRATCH}/kubectl-read.err")"
    fi
}

validate_existing_pair() {
    # Both objects exist: check Kubernetes structure, then real cryptography.
    # Any failure leaves both objects untouched.
    local secret_type
    secret_type="$(jq -r '.type // ""' "${SCRATCH}/secret.json")" \
        || die "cannot parse the TLS Secret '${TLS_SECRET_NAME}' JSON."
    if [ "${secret_type}" != "${TLS_SECRET_TYPE}" ]; then
        die "TLS Secret '${TLS_SECRET_NAME}' in namespace '${NAMESPACE}' has type '${secret_type}' but '${TLS_SECRET_TYPE}' is required."
    fi
    if ! jq -e '(.data["tls.crt"] != null) and (.data["tls.key"] != null)' \
        "${SCRATCH}/secret.json" >/dev/null; then
        die "TLS Secret '${TLS_SECRET_NAME}' is missing required data keys 'tls.crt'/'tls.key'."
    fi
    if ! jq -e '(.data["service-ca.crt"] != null) or (.binaryData["service-ca.crt"] != null)' \
        "${SCRATCH}/configmap.json" >/dev/null; then
        die "CA ConfigMap '${CA_CONFIGMAP_NAME}' is missing required data key '${CA_CONFIGMAP_KEY}'."
    fi

    # Decode the existing material into private scratch (removed on exit,
    # never printed). Secret data values are base64; 'openssl base64 -d -A'
    # handles the single-line base64 Kubernetes stores. The ConfigMap key is
    # different: 'kubectl create configmap --from-file' stores a certificate
    # (UTF-8 text) as a plain string in .data, so that value is written out
    # directly; .binaryData (base64, written by other creators) is the
    # fallback.
    local b64
    b64="$(jq -r '.data["tls.crt"]' "${SCRATCH}/secret.json")" \
        || die "cannot read 'tls.crt' from Secret '${TLS_SECRET_NAME}'."
    printf '%s' "${b64}" | openssl base64 -d -A -out "${SCRATCH}/existing-tls.crt" 2>/dev/null \
        || die "'tls.crt' in Secret '${TLS_SECRET_NAME}' is not valid base64 data."
    b64="$(jq -r '.data["tls.key"]' "${SCRATCH}/secret.json")" \
        || die "cannot read 'tls.key' from Secret '${TLS_SECRET_NAME}'."
    printf '%s' "${b64}" | openssl base64 -d -A -out "${SCRATCH}/existing-tls.key" 2>/dev/null \
        || die "'tls.key' in Secret '${TLS_SECRET_NAME}' is not valid base64 data."
    if jq -e '.data["service-ca.crt"] != null' "${SCRATCH}/configmap.json" >/dev/null 2>&1; then
        jq -r '.data["service-ca.crt"]' "${SCRATCH}/configmap.json" >"${SCRATCH}/existing-ca.crt" \
            || die "cannot read '${CA_CONFIGMAP_KEY}' from ConfigMap '${CA_CONFIGMAP_NAME}'."
    else
        b64="$(jq -r '.binaryData["service-ca.crt"]' "${SCRATCH}/configmap.json")" \
            || die "cannot read '${CA_CONFIGMAP_KEY}' from ConfigMap '${CA_CONFIGMAP_NAME}'."
        printf '%s' "${b64}" | openssl base64 -d -A -out "${SCRATCH}/existing-ca.crt" 2>/dev/null \
            || die "'${CA_CONFIGMAP_KEY}' in ConfigMap '${CA_CONFIGMAP_NAME}' is not valid base64 data."
    fi

    if ! validate_pair "${SCRATCH}/existing-ca.crt" "${SCRATCH}/existing-tls.crt" "${SCRATCH}/existing-tls.key"; then
        die "existing certificate material failed validation and was left completely unchanged:
  - ${PAIR_ERROR}
This script never replaces, adopts, or deletes existing material. Fix the objects manually, or delete BOTH '${TLS_SECRET_NAME}' (Secret) and '${CA_CONFIGMAP_NAME}' (ConfigMap) and re-run to create a fresh pair."
    fi
    info "Existing TLS Secret '${TLS_SECRET_NAME}' and CA ConfigMap '${CA_CONFIGMAP_NAME}'"
    info "are valid for DNS:${SAN_SHORT} and DNS:${SAN_LONG}; leaving both unchanged."
    exit 0
}

create_fresh_pair() {
    # Neither object exists: create the namespace (if absent), generate the
    # CA and serving certificate in private scratch, self-verify them with
    # real OpenSSL checks, then create the two objects. A failure creating
    # the second object is reported as partial state; nothing is deleted.
    if [ "${NAMESPACE_STATUS}" = "missing" ]; then
        info "Namespace '${NAMESPACE}' does not exist; creating it."
        if ! kubectl "${KCFG[@]}" create namespace "${NAMESPACE}" \
            >"${SCRATCH}/kubectl.out" 2>"${SCRATCH}/kubectl.err"; then
            die "creating namespace '${NAMESPACE}' failed:
$(cat "${SCRATCH}/kubectl.err")"
        fi
    fi

    info "Generating a test CA and a ${LEAF_CERT_VALIDITY_DAYS}-day serving certificate for '${SERVICE_NAME}'..."

    # One OpenSSL config for both certificates: extension sections in a
    # config file work on both macOS LibreSSL and Linux OpenSSL without
    # modern-only flags. The common names are fixed labels, not the Service
    # DNS names: identity lives in subjectAltName, and a valid
    # 'service.namespace.svc' name can exceed OpenSSL's 64-character
    # common-name limit. The CA and leaf subjects must differ — a leaf
    # whose subject equals its issuer's is treated as self-signed and
    # fails 'openssl verify'.
    cat > "${SCRATCH}/certs.cnf" <<EOF
[req]
prompt = no
distinguished_name = dn
[dn]
CN = setup-service-certs CA
[v3_ca]
basicConstraints = critical, CA:TRUE
keyUsage = critical, keyCertSign, cRLSign
[v3_leaf]
basicConstraints = CA:FALSE
keyUsage = critical, digitalSignature, keyEncipherment
extendedKeyUsage = serverAuth
subjectAltName = DNS:${SAN_SHORT}, DNS:${SAN_LONG}
EOF

    openssl genrsa -out "${SCRATCH}/ca.key" 2048 >/dev/null 2>&1 \
        || die "generating the CA private key failed."
    openssl req -new -x509 -key "${SCRATCH}/ca.key" -out "${SCRATCH}/ca.crt" \
        -days "${CA_CERT_VALIDITY_DAYS}" -config "${SCRATCH}/certs.cnf" \
        -extensions v3_ca >/dev/null 2>&1 \
        || die "generating the CA certificate failed."
    openssl genrsa -out "${SCRATCH}/tls.key" 2048 >/dev/null 2>&1 \
        || die "generating the serving private key failed."
    openssl req -new -key "${SCRATCH}/tls.key" -out "${SCRATCH}/tls.csr" \
        -config "${SCRATCH}/certs.cnf" -subj "/CN=setup-service-certs" >/dev/null 2>&1 \
        || die "creating the serving certificate request failed."
    openssl x509 -req -in "${SCRATCH}/tls.csr" -CA "${SCRATCH}/ca.crt" \
        -CAkey "${SCRATCH}/ca.key" -CAcreateserial -out "${SCRATCH}/tls.crt" \
        -days "${LEAF_CERT_VALIDITY_DAYS}" -extfile "${SCRATCH}/certs.cnf" \
        -extensions v3_leaf >/dev/null 2>&1 \
        || die "signing the serving certificate failed."

    # Prove the fresh material with the same checks used for reuse; a
    # failure here means nothing has been created yet.
    if ! validate_pair "${SCRATCH}/ca.crt" "${SCRATCH}/tls.crt" "${SCRATCH}/tls.key"; then
        die "the generated certificate failed self-verification (nothing was created):
  - ${PAIR_ERROR}"
    fi
    info "Certificate generated and self-verified (CA ${CA_CERT_VALIDITY_DAYS} days, leaf ${LEAF_CERT_VALIDITY_DAYS} days)."

    if ! kubectl "${KCFG[@]}" -n "${NAMESPACE}" create secret tls "${TLS_SECRET_NAME}" \
        --cert="${SCRATCH}/tls.crt" --key="${SCRATCH}/tls.key" \
        >"${SCRATCH}/kubectl.out" 2>"${SCRATCH}/kubectl.err"; then
        die "creating TLS Secret '${TLS_SECRET_NAME}' in namespace '${NAMESPACE}' failed:
$(cat "${SCRATCH}/kubectl.err")
PARTIAL STATE: the namespace was created if it was absent; the outcome of the Secret create is UNKNOWN (kubectl failed — the API server may still have stored it) and the ConfigMap was not attempted. Inspect Secret '${TLS_SECRET_NAME}' and ConfigMap '${CA_CONFIGMAP_NAME}' in namespace '${NAMESPACE}' on cluster '${KIND_CLUSTER_NAME}' before re-running. Nothing was rolled back."
    fi
    info "Created TLS Secret '${TLS_SECRET_NAME}' (type ${TLS_SECRET_TYPE})."

    if ! kubectl "${KCFG[@]}" -n "${NAMESPACE}" create configmap "${CA_CONFIGMAP_NAME}" \
        --from-file="${CA_CONFIGMAP_KEY}=${SCRATCH}/ca.crt" \
        >"${SCRATCH}/kubectl.out" 2>"${SCRATCH}/kubectl.err"; then
        die "creating CA ConfigMap '${CA_CONFIGMAP_NAME}' in namespace '${NAMESPACE}' failed:
$(cat "${SCRATCH}/kubectl.err")
PARTIAL STATE: the TLS Secret '${TLS_SECRET_NAME}' was created; the outcome of the ConfigMap create is UNKNOWN (kubectl failed — the API server may still have stored it). The test CA is discarded when this script exits, so the ConfigMap cannot be created manually from it afterwards. Inspect ConfigMap '${CA_CONFIGMAP_NAME}' in namespace '${NAMESPACE}' on cluster '${KIND_CLUSTER_NAME}': fix the cause of the failure and, when the ConfigMap is absent, remove the Secret this run created (if safe to do so) so a re-run can create a fresh, matching pair. Nothing was rolled back."
    fi
    info "Created CA ConfigMap '${CA_CONFIGMAP_NAME}' (key '${CA_CONFIGMAP_KEY}')."
    info "Done. The serving certificate covers DNS:${SAN_SHORT} and DNS:${SAN_LONG} (${LEAF_CERT_VALIDITY_DAYS}-day validity)."
}

main() {
    if [ "$#" -ne 0 ]; then
        die "this script takes no arguments; all settings are baked into the file."
    fi

    validate_settings
    check_prerequisites
    setup_private_scratch
    discover_kind_target

    # Initial target discovery and all required object reads complete before
    # any mutation; a failure here stops the script with zero writes.
    read_object "namespace" "${NAMESPACE}" "" "${SCRATCH}/namespace.json"
    NAMESPACE_STATUS="${READ_STATUS}"
    NAMESPACE_READ_ERROR="${READ_ERROR}"

    read_object "secret" "${TLS_SECRET_NAME}" "${NAMESPACE}" "${SCRATCH}/secret.json"
    SECRET_STATUS="${READ_STATUS}"
    SECRET_READ_ERROR="${READ_ERROR}"

    read_object "configmap" "${CA_CONFIGMAP_NAME}" "${NAMESPACE}" "${SCRATCH}/configmap.json"
    CONFIGMAP_STATUS="${READ_STATUS}"
    CONFIGMAP_READ_ERROR="${READ_ERROR}"

    # Authorization, network, and other read errors are never 'missing'.
    if [ "${NAMESPACE_STATUS}" = "error" ]; then
        die "reading namespace '${NAMESPACE}' failed (not treated as absence):
${NAMESPACE_READ_ERROR}"
    fi
    if [ "${SECRET_STATUS}" = "error" ]; then
        die "reading TLS Secret '${TLS_SECRET_NAME}' failed (not treated as absence):
${SECRET_READ_ERROR}"
    fi
    if [ "${CONFIGMAP_STATUS}" = "error" ]; then
        die "reading CA ConfigMap '${CA_CONFIGMAP_NAME}' failed (not treated as absence):
${CONFIGMAP_READ_ERROR}"
    fi

    if [ "${SECRET_STATUS}" = "found" ] && [ "${CONFIGMAP_STATUS}" = "found" ]; then
        validate_existing_pair
    elif [ "${SECRET_STATUS}" = "missing" ] && [ "${CONFIGMAP_STATUS}" = "missing" ]; then
        create_fresh_pair
    else
        die "incomplete existing state in namespace '${NAMESPACE}': TLS Secret '${TLS_SECRET_NAME}' is ${SECRET_STATUS} while CA ConfigMap '${CA_CONFIGMAP_NAME}' is ${CONFIGMAP_STATUS}.
This script only creates a complete pair from nothing or reuses a complete valid pair; it never fills in one half. Delete the existing object (or provide valid matching material for the missing one) and re-run."
    fi
}

